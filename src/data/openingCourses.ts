export function getCourseById(courseId: string): OpeningCourse | undefined {
  return OPENING_COURSES.find((c) => c.id === courseId);
}

/**
 * Only one single preview line (Italian Game: Giuoco Piano Central Strike) is unlocked for free users.
 * Subscribers ('pro') unlock all courses and all 48 lines.
 */
export function isVariationUnlocked(
  _courseId: string,
  variationId: string,
  userTier: SubscriptionTier
): boolean {
  if (userTier === 'pro') return true;
  return variationId === FREE_PREVIEW_VARIATION_ID;
}

/**
 * On Free Preview, only the Italian Game course can be opened (to access its 1 preview line);
 * all other 7 courses are locked until Checkmate Pro is activated.
 */
export function isCourseUnlocked(
  courseId: string,
  userTier: SubscriptionTier
): boolean {
  if (userTier === 'pro') return true;
  return courseId === FREE_PREVIEW_COURSE_ID;
}
